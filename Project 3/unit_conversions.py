quantity = float(input("Please enter the quantity to be converted: "))
#Pounds to Newtons
print(f"{quantity:.2f} pounds force is equivalent to {quantity * 4.44822:.2f} newtons")

#Meters to feet
print(f"{quantity:.2f} meters is equivalent to {quantity * 3.28084:.2f} feet")

#Atmospheres to Kilopascals
print(f"{quantity:.2f} atmospheres is equivalent to {quantity * 101.325:.2f} kilopascals")

#Watts to BTU
print (f"{quantity:.2f} watts is equivalent to {quantity * 3.412142:.2f} BTU per hour")

#Liters per second to Gallons per minute
